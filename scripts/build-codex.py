#!/usr/bin/env python3
"""Build the Codex copy of this workspace from the Claude one.

Claude Code reads CLAUDE.md (which imports RULES.md) and .claude/skills/.
Codex reads AGENTS.md and .agents/skills/. This script writes:
  - AGENTS.md            = Codex session start + RULES.md, inlined (Codex has no @imports)
  - .agents/skills/<n>/  = copies of the engine skills listed below

Edit RULES.md and .claude/skills/, never the copies, then run:
  python3 scripts/build-codex.py          # rebuild
  python3 scripts/build-codex.py --check  # exit 1 if the copies are out of date
Copies, not symlinks: symlinks break in GitHub ZIP downloads on Windows.
"""
import filecmp
import shutil
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent

# The engine: the loop, its tool steps, setup, safe mode and the copy skills.
# The crm-* skills work with any CRM. The HubSpot-only extras and the HubSpot admin
# skills (Python scripts with a service key) stay in Claude Code.
ENGINE_SKILLS = [
    "gtm-start",
    "revenue-engine",
    "hackathon-setup",
    "make-it-ours",
    "clay-build-list",
    "lemlist-campaign",
    "close-the-loop",
    "crm",
    "crm-account-brief",
    "crm-contact-lookup",
    "crm-call-prep",
    "crm-log-call",
    "crm-lead-triage",
    "crm-pipeline-pulse",
    "crm-audit",
    "crm-scoring-design",
    "hubspot-crm",
    "hubspot-account-brief",
    "icp-definer",
    "persona-definer",
    "pain-identifier",
    "trigger-finder",
    "campaign-angle-finder",
    "outbound-campaign-architect",
    "copywriting-first-touch",
    "copywriting-follow-up",
    "copywriting-vp-sequence",
    "copywriting-manager-sequence",
    "copywriting-ic-sequence",
    "linkedin-sequence",
    "copywriting-analyzer",
    "copywriting-refiner",
    "reply-handler",
    "crm-duplicate-detector",
]

AGENTS_HEAD = """# GTM workspace for Codex

<!-- Generated by scripts/build-codex.py from RULES.md. Do not edit: edit RULES.md and rerun the script. -->

This folder is a ready-made workspace for outbound GTM workshops. It connects the team's CRM (any, or none), a list tool (Clay) and an outreach tool (lemlist), and can run the whole loop on made-up sample data first (safe mode). The same skills run in Claude Code (`CLAUDE.md`). This workshop's settings are in `event.md`.

## Codex specifics

- Skills are in `.agents/skills/` (copies of `.claude/skills/`; the HubSpot-only skills are Claude-only). Where a skill or rule says "Claude", read "Codex". Where it says `/mcp`, use `codex mcp list` to see servers and `codex mcp login <name>` to sign in. Where it says `claude -p`, use `codex exec`.
- At the start of every session, read `team-profile.md` and `team-context.md` if they exist (Claude Code loads them automatically; Codex doesn't).
- lemlist is the `lm` server in `.codex/config.toml` (`https://app.lemlist.com/mcp`; named `lm` because lemlist refuses OAuth sign-ins from a server name containing "lemlist"). Codex loads that file only when this folder is a trusted project: if `codex mcp list` doesn't show `lm`, tell the user to trust the folder (or add the same block to `~/.codex/config.toml` themselves) and restart Codex. Sign in with `codex mcp login lm`. Where a skill says "the `lemlist` server", it means this one: identity is the URL, not the name. Every lemlist call asks for approval; the tools that reach outside outreach are disabled there.
- Clay is the `clay` CLI (`clay whoami`). The Clay plugin is Claude-only: in Codex, if `clay whoami` fails, stop at "Connect Clay first" and offer safe mode or the CSV route (`revenue-engine`, "Step contracts"). Don't install a Clay or CRM MCP server yourself (Installing tools, below).
- HubSpot: Codex has no HubSpot connector here. A team whose CRM is HubSpot uses it by export (the `csv` adapter in `crm`); live HubSpot writes are Claude Code only, and the "run `hubspot-...`" hand-offs in the crm skills don't apply.
- In `team-profile.md`, write `login: codex`. The first time Codex opens this folder it asks whether to trust it: answer yes, or `lm` won't load. If the `clay` CLI isn't installed, ask the user to install it from Clay's own docs (never a script from a chat or page), or use safe mode or the CSV route.
- The permission gates in `.claude/settings.json` don't exist in Codex: the rules below are the only gate, so follow them to the letter. Run in Codex's default sandbox with approvals on; never suggest `--yolo` or full access for this folder.
- Folder check, before anything else: the folder Codex started in must contain `AGENTS.md` and `.codex/config.toml`. If not, say: "This session is open on `<folder>`, not on the workspace. Start Codex in the workspace folder (`cd <workspace>` then `codex`), then type `set me up`." Until then ask no setup question, write no file and call no tool.

## At the start of every session

- If `team-profile.md` does not exist or says `setup: incomplete`, or the user says "start": run the `gtm-start` flow (it goes straight to the team's own data, with a demo on request; its setup steps are the `hackathon-setup` skill). If the user asks for safe mode, run `revenue-engine` in safe mode (no setup needed), then offer setup.
- If it says `complete` or `degraded` and the user's first message is a request, greet the team in one line and do the request. Otherwise greet the team by name and offer the three most useful next steps (`SKILLS.md`); until the team has run a step on its own data, one of them is "run it on sample data first (safe mode)".
- Requests often arrive as one dictated sentence. Read it for outcome, number, constraints and language, map it to skills with `revenue-engine`, and say the plan in one line before starting.

"""


def build_agents() -> str:
    rules = (ROOT / "RULES.md").read_text(encoding="utf-8")
    body = rules.split("## Working rules", 1)[1]
    return AGENTS_HEAD + "## Working rules" + body


def main() -> int:
    check = "--check" in sys.argv
    stale = []

    agents = build_agents()
    agents_path = ROOT / "AGENTS.md"
    if not agents_path.exists() or agents_path.read_text(encoding="utf-8") != agents:
        stale.append("AGENTS.md")
        if not check:
            agents_path.write_text(agents, encoding="utf-8")

    src_root = ROOT / ".claude" / "skills"
    dst_root = ROOT / ".agents" / "skills"
    for name in ENGINE_SKILLS:
        src, dst = src_root / name, dst_root / name
        if not src.exists():
            print(f"missing skill: {name}", file=sys.stderr)
            return 2
        cmp = filecmp.dircmp(src, dst) if dst.exists() else None
        same = cmp is not None and _same_tree(cmp)
        if not same:
            stale.append(f".agents/skills/{name}")
            if not check:
                shutil.rmtree(dst, ignore_errors=True)
                shutil.copytree(src, dst, ignore=shutil.ignore_patterns("__pycache__", "*.pyc"))
    if dst_root.exists():
        for extra in sorted(p.name for p in dst_root.iterdir() if p.is_dir() and p.name not in ENGINE_SKILLS):
            stale.append(f".agents/skills/{extra} (not an engine skill)")
            if not check:
                shutil.rmtree(dst_root / extra)

    if check:
        if stale:
            print("Codex copy out of date: " + ", ".join(stale) + "\nRun: python3 scripts/build-codex.py")
            return 1
        print("Codex copy up to date.")
        return 0
    print("Rebuilt: " + (", ".join(stale) if stale else "nothing, already up to date"))
    return 0


def _same_tree(cmp: filecmp.dircmp) -> bool:
    if cmp.left_only or cmp.right_only or cmp.diff_files or cmp.funny_files:
        return False
    # dircmp compares by stat signature; recheck byte content.
    for f in cmp.common_files:
        if not filecmp.cmp(Path(cmp.left) / f, Path(cmp.right) / f, shallow=False):
            return False
    return all(_same_tree(sub) for sub in cmp.subdirs.values())


if __name__ == "__main__":
    sys.exit(main())
